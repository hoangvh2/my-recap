// Release signing: CI passes a private keystore through env vars (GitHub secrets). Without them the
// committed sideload key (keystore/sideload.jks, intentionally public) is used so every build can
// update the previous install in place.
val signingProps = Properties().apply {
    val f = rootProject.file("keystore/sideload.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: signingProps.getProperty(prop)

